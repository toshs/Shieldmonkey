// Generate static SVG nodes so the popup shares Lucide's icons without loading React.
import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
const names = { settings: 'settings', sun: 'sun', moon: 'moon', monitor: 'monitor', file: 'file-code', plus: 'plus', edit: 'pencil', refresh: 'refresh-cw', trash: 'trash-2' };
const icons = {};
for (const [name, module] of Object.entries(names)) {
    const { __iconNode } = await import(new URL(`../node_modules/lucide-react/dist/esm/icons/${module}.js`, import.meta.url));
    icons[name] = __iconNode.map(([tag, { key: _key, ...attributes }]) => [tag, attributes]);
}
writeFileSync(new URL('../src/popup/icons.ts', import.meta.url), '// Generated by scripts/sync-popup-icons.mjs from lucide-react.\n// ISC / MIT license: public/third-party/LUCIDE-LICENSE.txt\nexport const popupIcons = ' + JSON.stringify(icons, null, 2) + ' as const;\n');
const licenses = new URL('../public/third-party/', import.meta.url);
mkdirSync(licenses, { recursive: true });
writeFileSync(new URL('LUCIDE-LICENSE.txt', licenses), readFileSync(new URL('../node_modules/lucide-react/LICENSE', import.meta.url)));
